using Delobytes.App.Backend.Integrations.Application.Products;
using Delobytes.App.Backend.Integrations.Contracts.Events;
using MassTransit;

namespace Delobytes.App.Backend.Integrations.Infrastructure.Messaging.Consumers;

/// <summary>
/// MassTransit consumer adapter for <see cref="ProductsImportBatchAggregator"/>.
/// Extracts MessageId from ConsumeContext and passes it through for idempotency.
/// </summary>
public class ProductImportBatchCompletedConsumer : IConsumer<ProductBatchImportCompletedEvent>
{
    private readonly ProductsImportBatchAggregator _aggregator;

    /// <summary>
    /// Initializes a new instance of the <see cref="ProductImportBatchCompletedConsumer"/> class.
    /// </summary>
    /// <param name="aggregator">Products import batch aggregator.</param>
    public ProductImportBatchCompletedConsumer(ProductsImportBatchAggregator aggregator)
    {
        _aggregator = aggregator;
    }

    /// <inheritdoc/>
    public async Task Consume(ConsumeContext<ProductBatchImportCompletedEvent> context)
    {
        // MessageId is generated by MassTransit and is stable across redeliveries of the same message.
        Guid messageId = context.MessageId ?? Guid.NewGuid();
        await _aggregator.ProcessAsync(context.Message, messageId, context.CancellationToken);
    }
}
