using Delobytes.App.Backend.Integrations.Contracts.Models;

namespace Delobytes.App.Backend.Integrations.Contracts.Events;

/// <summary>
/// Published by Integrations.ProcessOrdersImportConsumer for each batch of fetched orders.
/// Consumed by Sales.OrdersBatchImportRequestedConsumer to upsert orders and order lines.
/// </summary>
public record OrdersBatchImportRequestedEvent
{
    /// <summary>
    /// Identifier of the JobRun that tracks this import.
    /// </summary>
    public Guid JobRunId { get; init; }

    /// <summary>
    /// Identifier of the Connection from which orders are imported.
    /// </summary>
    public Guid ConnectionId { get; init; }

    /// <summary>
    /// Identifier of the Channel in Catalog/Sales modules. Required by the Sales consumer to
    /// upsert <c>Order</c> by <c>(TenantId, ChannelId, ExternalOrderId)</c> and to resolve
    /// <c>ChannelProductRef</c> for order lines.
    /// </summary>
    public Guid ChannelId { get; init; }

    /// <summary>
    /// Identifier of this batch, generated by the publisher. Used by the consumer to report
    /// results back via <see cref="OrdersBatchImportCompletedEvent.BatchId"/> and by the
    /// aggregator to deduplicate batch results.
    /// </summary>
    public Guid BatchId { get; init; }

    /// <summary>
    /// Batch of order snapshots from the external marketplace.
    /// </summary>
    public List<ChannelOrderSnapshot> Orders { get; init; } = new();

    /// <summary>
    /// True if this is the last batch in the current import job.
    /// </summary>
    public bool IsTerminal { get; init; }
}
